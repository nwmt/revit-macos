"""Generates from exports.txt (Wine's ncrypt.dll exports):
  forwards.S         -- jmp *__real_X(%rip) thunks for everything the shim does not implement itself
  forwards_table.c   -- {name, &__real_X} table filled in DllMain
  ncrypt.def         -- exports: own functions, thunks, BCrypt* as PE forwarders to bcrypt.dll
"""
import pathlib
here = pathlib.Path(__file__).parent
names = [n.strip() for n in (here / "exports.txt").read_text().split() if n.strip()]
own = {"NCryptOpenStorageProvider", "NCryptImportKey", "NCryptSignHash", "NCryptVerifySignature", "NCryptFreeObject"}
bcrypt = [n for n in names if n.startswith("BCrypt")]
fwd = [n for n in names if n not in own and n not in bcrypt]

s = ["# SPDX-License-Identifier: MIT", "# generated by gen_forwards.py -- do not edit", "\t.text"]
for n in fwd:
    s += [f"\t.globl {n}", f"{n}:", f"\tjmp *__real_{n}(%rip)"]
s += ["", "# unresolved thunk: return NTE_NOT_SUPPORTED (0x80090029)",
      "\t.globl shim_unresolved", "shim_unresolved:", "\tmovl $0x80090029, %eax", "\tret", "", "\t.data", "\t.p2align 3"]
for n in fwd:
    s += [f"\t.globl __real_{n}", f"__real_{n}:", "\t.quad shim_unresolved"]
(here / "forwards.S").write_text("\n".join(s) + "\n")

c = ["/* SPDX-License-Identifier: MIT */", "/* generated by gen_forwards.py -- do not edit */",
     "struct shim_forward { const char *name; void **slot; };"]
c += [f"extern void *__real_{n};" for n in fwd]
c += ["struct shim_forward shim_forwards[] = {"] + [f'    {{ "{n}", &__real_{n} }},' for n in fwd] + ["    { 0, 0 }", "};"]
(here / "forwards_table.c").write_text("\n".join(c) + "\n")

d = ["; generated by gen_forwards.py -- do not edit", "LIBRARY ncrypt.dll", "EXPORTS"]
d += [f"    {n}" for n in sorted(own)] + [f"    {n}" for n in fwd] + [f"    {n} = bcrypt.{n}" for n in bcrypt]
(here / "ncrypt.def").write_text("\n".join(d) + "\n")
print(f"own={len(own)} forwards={len(fwd)} bcrypt-forwarders={len(bcrypt)} total={len(own)+len(fwd)+len(bcrypt)}")
